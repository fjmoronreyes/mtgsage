
"""HTTP adapter for the Magic: The Gathering API."""

from collections.abc import Mapping
from typing import Any
from urllib.parse import quote

import httpx

from .models import Card, CardPage, CardQuery


API_BASE_URL = "https://api.magicthegathering.io/v1"

COLOR_CODES = {
    "WHITE": "W",
    "BLUE": "U",
    "BLACK": "B",
    "RED": "R",
    "GREEN": "G",
}


class MagicApiClient:
    """Search and retrieve Magic cards through the external API."""

    def __init__(self, client: httpx.Client | None = None) -> None:
        self._owns_client = client is None
        self._client = client if client is not None else httpx.Client(
            timeout=10.0
        )

    def __enter__(self) -> "MagicApiClient":
        return self

    def __exit__(self, *_: object) -> None:
        self.close()

    def close(self) -> None:
        if self._owns_client:
            self._client.close()

    @staticmethod
    def _parse_card(data: Mapping[str, Any]) -> Card:
        """Normalize an API response into our domain model."""
        return Card(
            id=data["id"],
            name=data["name"],
            mana_cost=data.get("manaCost"),
            mana_value=data.get("cmc"),
            colors=tuple(data.get("colors") or ()),
            types=tuple(data.get("types") or ()),
            subtypes=tuple(data.get("subtypes") or ()),
            oracle_text=data.get("text"),
            set_code=data.get("set"),
            image_url=data.get("imageUrl"),
            rulings=tuple(
                ruling["text"]
                for ruling in data.get("rulings") or ()
                if ruling.get("text")
            ),
        )

    @staticmethod
    def _build_params(query: CardQuery) -> dict[str, str]:
        """Translate domain filters into provider-specific parameters."""
        params: dict[str, str] = {}

        if query.name:
            params["name"] = query.name

        if query.colors:
            params["colors"] = ",".join(
                COLOR_CODES.get(color.upper(), color.upper())
                for color in query.colors
            )

        if query.types:
            params["types"] = ",".join(query.types)

        if query.subtypes:
            params["subtypes"] = ",".join(query.subtypes)

        return params

    def _fetch_page(
        self,
        params: Mapping[str, str | int],
        page: int,
        page_size: int,
    ) -> tuple[tuple[Card, ...], int]:
        """Fetch one provider page and its total result count."""
        response = self._client.get(
            f"{API_BASE_URL}/cards",
            params={
                **params,
                "page": page,
                "pageSize": page_size,
            },
        )
        response.raise_for_status()

        total = response.headers.get("Total-Count")

        if total is None:
            raise ValueError("Card API response missing Total-Count")

        cards = tuple(
            self._parse_card(item)
            for item in response.json()["cards"]
        )

        return cards, int(total)

    def search(self, query: CardQuery) -> CardPage:
        """Search cards, supporting exclusive mana-value upper bounds."""
        if query.page < 1:
            raise ValueError("Page must be greater than zero")

        if not 1 <= query.page_size <= 100:
            raise ValueError("Page size must be between 1 and 100")

        params = self._build_params(query)

        # No mana range: delegate pagination directly to the API.
        if query.mana_value_lt is None:
            cards, total = self._fetch_page(
                params,
                query.page,
                query.page_size,
            )

            return CardPage(
                cards=cards,
                page=query.page,
                total_count=total,
            )

        # Bound the number of requests generated by a range query.
        if not 0 <= query.mana_value_lt <= 20:
            raise ValueError(
                "Mana value upper bound must be between 0 and 20"
            )

        if query.mana_value_lt == 0:
            return CardPage(
                cards=(),
                page=query.page,
                total_count=0,
            )

        # The API accepts exact CMC values, but rejects '0|1'.
        # We concatenate CMC buckets in ascending order and paginate
        # over the combined results.
        start = (query.page - 1) * query.page_size
        end = start + query.page_size

        selected: list[Card] = []
        total_count = 0

        for cmc in range(query.mana_value_lt):
            scoped_params = {**params, "cmc": cmc}

            first_batch, count = self._fetch_page(
                scoped_params,
                page=1,
                page_size=query.page_size,
            )

            # Identify the portion of this CMC bucket that belongs
            # to the requested page of the combined result.
            local_start = max(0, start - total_count)
            local_end = min(count, end - total_count)

            while local_start < local_end:
                source_page = local_start // query.page_size + 1
                offset = local_start % query.page_size

                if source_page == 1:
                    batch = first_batch
                else:
                    batch, _ = self._fetch_page(
                        scoped_params,
                        page=source_page,
                        page_size=query.page_size,
                    )

                take = min(
                    local_end - local_start,
                    len(batch) - offset,
                )

                if take <= 0:
                    raise ValueError(
                        "Inconsistent pagination from card API"
                    )

                selected.extend(batch[offset:offset + take])
                local_start += take

            total_count += count

        return CardPage(
            cards=tuple(selected),
            page=query.page,
            total_count=total_count,
        )

    def get_card(self, card_id: str) -> Card:
        """Retrieve a card by its provider identifier."""
        if not card_id:
            raise ValueError("Card ID cannot be empty")

        response = self._client.get(
            f"{API_BASE_URL}/cards/{quote(card_id, safe='')}"
        )
        response.raise_for_status()

        return self._parse_card(response.json()["card"])
